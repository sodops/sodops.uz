import { unified } from 'unified';
import remarkParse from 'remark-parse';
import remarkGfm from 'remark-gfm';
import remarkRehype from 'remark-rehype';
import rehypeSlug from 'rehype-slug';
import rehypeHighlight from 'rehype-highlight';
import rehypeParse from 'rehype-parse';
import rehypeSanitize, { defaultSchema } from 'rehype-sanitize';
import rehypeStringify from 'rehype-stringify';

import typescript from 'highlight.js/lib/languages/typescript';
import javascript from 'highlight.js/lib/languages/javascript';
import bash from 'highlight.js/lib/languages/bash';
import sql from 'highlight.js/lib/languages/sql';
import yaml from 'highlight.js/lib/languages/yaml';
import json from 'highlight.js/lib/languages/json';
import rust from 'highlight.js/lib/languages/rust';
import python from 'highlight.js/lib/languages/python';
import dockerfile from 'highlight.js/lib/languages/dockerfile';
import diff from 'highlight.js/lib/languages/diff';

/**
 * Explicit, curated list of syntax highlighting languages.
 * Disabling autodetection (detect: false) and scoping to these 10 languages
 * dramatically reduces save-time CPU time and worker bundle size.
 */
export const allowedHighlightLanguages: Record<string, any> = {
  typescript,
  ts: typescript,
  javascript,
  js: javascript,
  bash,
  sh: bash,
  shell: bash,
  sql,
  yaml,
  yml: yaml,
  json,
  rust,
  rs: rust,
  python,
  py: python,
  dockerfile,
  docker: dockerfile,
  diff,
};

/**
 * Shared Markdown Sanitization Schema
 *
 * Extends GitHub-style defaultSchema to safely permit:
 * - Syntax highlighting classes (hljs-*) on <span>, <code>, <pre>
 * - Heading IDs generated by rehypeSlug
 * - GFM tables, task lists, and blockquotes
 * - Strictly strips <script>, <iframe>, event handlers (onload, onerror), and javascript: URLs.
 */
export const sharedSanitizeSchema = {
  ...defaultSchema,
  clobberPrefix: '',
  attributes: {
    ...defaultSchema.attributes,
    '*': ['className', 'id'],
    code: [...(defaultSchema.attributes?.code || []), 'className'],
    span: [...(defaultSchema.attributes?.span || []), ['className', /^hljs-.*$/]],
    pre: [...(defaultSchema.attributes?.pre || []), 'className'],
    h1: [...(defaultSchema.attributes?.h1 || []), 'id'],
    h2: [...(defaultSchema.attributes?.h2 || []), 'id'],
    h3: [...(defaultSchema.attributes?.h3 || []), 'id'],
    h4: [...(defaultSchema.attributes?.h4 || []), 'id'],
    h5: [...(defaultSchema.attributes?.h5 || []), 'id'],
    h6: [...(defaultSchema.attributes?.h6 || []), 'id'],
    a: [
      ...(defaultSchema.attributes?.a || []),
      'href',
      'target',
      'rel',
      ['target', '_blank'],
    ],
  },
  protocols: {
    ...defaultSchema.protocols,
    href: ['http', 'https', 'mailto'],
  },
};

/**
 * Shared Markdown Pipeline
 *
 * Runs once at save time (in admin API or migration scripts).
 * Eliminates runtime Shiki/unified overhead on cache misses,
 * preventing Cloudflare Workers 1102 CPU limit exceeded errors.
 */
export async function renderAndSanitizeMarkdown(markdown: string): Promise<string> {
  const file = await unified()
    .use(remarkParse)
    .use(remarkGfm)
    .use(remarkRehype, { allowDangerousHtml: false })
    .use(rehypeSlug)
    .use(rehypeHighlight as any, {
      detect: false,
      languages: allowedHighlightLanguages,
      ignoreMissing: true,
    })
    .use(rehypeSanitize as any, sharedSanitizeSchema)
    .use(rehypeStringify)
    .process(markdown);

  return String(file);
}

/**
 * Re-sanitizes raw HTML to guarantee zero script injection or malformed markup.
 */
export async function sanitizeHtml(html: string): Promise<string> {
  const file = await unified()
    .use(rehypeParse, { fragment: true })
    .use(rehypeSanitize as any, sharedSanitizeSchema)
    .use(rehypeStringify)
    .process(html);

  return String(file);
}

/**
 * Estimates reading time in minutes (assuming 200 words per minute).
 */
export function calculateReadingTimeMinutes(text: string): number {
  const words = text.trim().split(/\s+/).filter(Boolean).length;
  return Math.max(1, Math.ceil(words / 200));
}

/**
 * Extracts h2 and h3 headings for Table of Contents generation.
 */
export function extractHeadings(
  markdown: string
): Array<{ depth: number; text: string; slug: string }> {
  const headings: Array<{ depth: number; text: string; slug: string }> = [];
  const lines = markdown.split('\n');

  for (const line of lines) {
    const match = line.match(/^(#{2,3})\s+(.+)$/);
    if (match) {
      const depth = match[1].length;
      const text = match[2].trim().replace(/[*_`]/g, '');
      const slug = text
        .toLowerCase()
        .replace(/[^\w\s-]/g, '')
        .replace(/\s+/g, '-');
      headings.push({ depth, text, slug });
    }
  }

  return headings;
}
