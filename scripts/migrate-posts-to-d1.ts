import * as fs from 'node:fs';
import * as path from 'node:path';

/**
 * Migration Script: Migrate Markdown Seed Posts into Cloudflare D1
 *
 * Reads all Markdown files in src/content/posts/, parses YAML frontmatter
 * and markdown body, and outputs an idempotent seed.sql file for D1.
 *
 * Usage:
 *   npx tsx scripts/migrate-posts-to-d1.ts
 *   npx wrangler d1 execute sodops-db --local --file=seed.sql
 */

interface Frontmatter {
  title: string;
  slug: string;
  published_at: string;
  excerpt: string;
  cover_image?: string;
  draft?: boolean;
  tags?: string[];
  reading_time_minutes?: number;
}

function parseMarkdownFile(filePath: string): {
  frontmatter: Frontmatter;
  content: string;
} {
  const raw = fs.readFileSync(filePath, 'utf-8');
  const match = raw.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n([\s\S]*)$/);
  if (!match) {
    throw new Error(`Invalid frontmatter in ${filePath}`);
  }

  const yamlBlock = match[1];
  const content = match[2].trim();

  // Basic YAML parser for known frontmatter keys
  const lines = yamlBlock.split('\n');
  const fm: Record<string, unknown> = {};

  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;

    const colonIdx = trimmed.indexOf(':');
    if (colonIdx === -1) continue;

    const key = trimmed.slice(0, colonIdx).trim();
    let val = trimmed.slice(colonIdx + 1).trim();

    // Remove quotes
    if (
      (val.startsWith('"') && val.endsWith('"')) ||
      (val.startsWith("'") && val.endsWith("'"))
    ) {
      val = val.slice(1, -1);
    }

    if (val.startsWith('[') && val.endsWith(']')) {
      const items = val
        .slice(1, -1)
        .split(',')
        .map((s) => s.trim().replace(/^['"]|['"]$/g, ''))
        .filter(Boolean);
      fm[key] = items;
    } else if (val === 'true') {
      fm[key] = true;
    } else if (val === 'false') {
      fm[key] = false;
    } else if (!isNaN(Number(val)) && val !== '') {
      fm[key] = Number(val);
    } else {
      fm[key] = val;
    }
  }

  return { frontmatter: fm as unknown as Frontmatter, content };
}

function escapeSql(str: string): string {
  return str.replace(/'/g, "''");
}

function generateMigrationSql(): string {
  const postsDir = path.resolve(process.cwd(), 'src/content/posts');
  if (!fs.existsSync(postsDir)) {
    throw new Error(`Directory ${postsDir} does not exist`);
  }

  const files = fs.readdirSync(postsDir).filter((f) => f.endsWith('.md'));
  const statements: string[] = [
    '-- Auto-generated by scripts/migrate-posts-to-d1.ts',
    '-- Seed data for Cloudflare D1 (sodops-db)',
    'PRAGMA foreign_keys = ON;',
    '',
  ];

  const uniqueTags = new Map<string, { id: string; name: string; slug: string }>();

  for (const file of files) {
    const fullPath = path.join(postsDir, file);
    const { frontmatter, content } = parseMarkdownFile(fullPath);

    const postId = `post_${frontmatter.slug.replace(/[^a-z0-9]/gi, '_')}`;
    const published = frontmatter.draft ? 0 : 1;
    const publishedAt = frontmatter.published_at || new Date().toISOString();
    const readingTime = frontmatter.reading_time_minutes || 1;
    const coverImage = frontmatter.cover_image || '';

    // Insert or replace post
    statements.push(
      `INSERT OR REPLACE INTO posts (id, slug, title, content, excerpt, cover_image, published, published_at, reading_time_minutes) ` +
        `VALUES ('${escapeSql(postId)}', '${escapeSql(frontmatter.slug)}', '${escapeSql(frontmatter.title)}', '${escapeSql(content)}', '${escapeSql(frontmatter.excerpt)}', '${escapeSql(coverImage)}', ${published}, '${escapeSql(publishedAt)}', ${readingTime});`
    );

    // Collect tags
    if (Array.isArray(frontmatter.tags)) {
      for (const tag of frontmatter.tags) {
        const tagSlug = tag.toLowerCase().replace(/[^a-z0-9]/g, '-');
        const tagId = `tag_${tagSlug.replace(/-/g, '_')}`;
        if (!uniqueTags.has(tagSlug)) {
          uniqueTags.set(tagSlug, { id: tagId, name: tag, slug: tagSlug });
        }
        statements.push(
          `INSERT OR IGNORE INTO post_tags (post_id, tag_id) VALUES ('${escapeSql(postId)}', '${escapeSql(tagId)}');`
        );
      }
    }
  }

  // Prepend tags insertions before post_tags
  const tagStatements: string[] = [];
  for (const [, tag] of uniqueTags) {
    tagStatements.push(
      `INSERT OR IGNORE INTO tags (id, name, slug) VALUES ('${escapeSql(tag.id)}', '${escapeSql(tag.name)}', '${escapeSql(tag.slug)}');`
    );
  }

  const finalSql = [
    '-- Schema Verification',
    statements[0],
    statements[1],
    statements[2],
    '',
    '-- Tags',
    ...tagStatements,
    '',
    '-- Posts & Post-Tag Relationships',
    ...statements.slice(3),
  ].join('\n');

  return finalSql;
}

// Generate seed.sql
const sql = generateMigrationSql();
const outPath = path.resolve(process.cwd(), 'seed.sql');
fs.writeFileSync(outPath, sql, 'utf-8');
console.log(
  `[migrate-posts-to-d1] Successfully generated ${outPath} (${sql.length} bytes)`
);
